    document.addEventListener('DOMContentLoaded', function() {
        console.log("DOM loaded, looking for FAQ elements...");
        let allQuestions = document.querySelectorAll(".faqsQuestion");
        console.log("FAQ questions found:", allQuestions.length);

        if (allQuestions.length > 0) {
            console.log("Adding click listeners to FAQ questions...");
            allQuestions.forEach((question, index) => {
                console.log("Adding listener to question", index);
                question.addEventListener("click", function(e) {
                    e.preventDefault();
                    console.log("FAQ clicked:", index);

                    const answer = question.nextElementSibling;
                    const icon = question.children[1];

                    console.log("Answer element:", answer);
                    console.log("Icon element:", icon);

                    answer.classList.toggle("hidden");
                    icon.textContent = icon.textContent === "+" ? "–" : "+";

                    allQuestions.forEach((otherQuestion, otherIndex) => {
                        if (otherIndex !== index) {
                            const otherAnswer = otherQuestion.nextElementSibling;
                            const otherIcon = otherQuestion.children[1];
                            otherAnswer.classList.add("hidden");
                            otherIcon.textContent = "+";
                        }
                    });
                });
            });
            console.log("All FAQ listeners added successfully");
        } else {
            console.log("ERROR: No FAQ elements found!");
            console.log("Available elements with 'faqs' in class:", document.querySelectorAll(
                "[class*='faqs']"));
        }
    });
